const BASE = RAW.map(([id, name, group, eq, level, compound, cues, alts = [], extra = {}]) => ({
  id,
  name,
  group,
  eq,
  level,
  compound,
  cues,
  alts: alts.filter(Boolean),
  time: !!(extra.time || group === 'core' || eq === 'cardio'),
  dist: !!extra.dist,
  custom: false,
}));

const BY_ID = new Map(BASE.map((e) => [e.id, e]));

export function baseExercises() {
  return BASE;
}

export function getBaseExercise(id) {
  return BY_ID.get(id) || null;
}

export function groupOf(ex) {
  return GROUPS[ex?.group] || GROUPS.other || { label: 'Другое', short: '—', color: '#8a93a3' };
}

export function equipmentLabel(eq) {
  return (EQUIPMENT[eq] || EQUIPMENT.other).label;
}

export function levelLabel(lvl) {
  return LEVELS[lvl] || 'Средний';
}

/** Карточка slug для ссылки на упражнение */
export function exerciseTypeInfo(ex) {
  if (!ex) return { hasWeight: true, hasReps: true, hasTime: false, hasDist: false };
  const hasWeight = ex.eq !== 'bodyweight' || ex.compound;
  const hasTime = !!ex.time || ex.group === 'cardio';
  const hasDist = !!ex.dist;
  return { hasWeight, hasReps: !hasTime || ex.group !== 'cardio', hasTime, hasDist };
}
